-- [RPC 함수 정의]
-- 7. RPC 함수: 매칭 정보 트랜잭션 저장 (원자성 확보)
CREATE OR REPLACE FUNCTION create_production_match(
    p_lumi_sn TEXT,
    p_solity_sn TEXT,
    p_production_time TEXT,
    p_operator_name TEXT,
    p_note TEXT
) RETURNS jsonb AS $$
DECLARE
    v_record_id BIGINT;
    v_result jsonb;
BEGIN
    -- 1. production_records에 삽입
    INSERT INTO production_records (lumi_sn, solity_sn, production_time, operator_name, note)
    VALUES (p_lumi_sn, p_solity_sn, p_production_time, p_operator_name, p_note)
    RETURNING id INTO v_record_id;

    -- 2. used_sn_codes에 삽입
    INSERT INTO used_sn_codes (sn_value, record_id, sn_role)
    VALUES 
        (p_lumi_sn, v_record_id, 'lumi'),
        (p_solity_sn, v_record_id, 'solity');

    -- 3. 결과 반환값 구성
    v_result := jsonb_build_object(
        'id', v_record_id,
        'lumi_sn', p_lumi_sn,
        'solity_sn', p_solity_sn,
        'production_time', p_production_time,
        'operator_name', p_operator_name,
        'note', p_note
    );
    
    RETURN v_result;
END;
$$ LANGUAGE plpgsql;

-- 8. RPC 함수: Lumi SN 백리스트 트랜잭션 갱신 (전체 삭제 및 대량 삽입)
CREATE OR REPLACE FUNCTION replace_lumi_product_sn(p_rows jsonb) RETURNS void AS $$
BEGIN
    -- 테이블 비우기
    DELETE FROM lumi_product_sn;
    
    -- 대량 삽입 실행
    INSERT INTO lumi_product_sn (lumi_sn, time)
    SELECT 
        (value->>'lumi_sn')::TEXT, 
        COALESCE(value->>'time', '')::TEXT
    FROM jsonb_array_elements(p_rows);
END;
$$ LANGUAGE plpgsql;
