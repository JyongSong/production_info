ALTER TABLE production_records DROP CONSTRAINT IF EXISTS production_records_lumi_sn_solity_sn_key;

-- 3. 개별 UNIQUE 제약조건 추가 (중복 등록 원천 방지)
-- 주의: 기존 테이블에 이미 중복된 Lumi SN 또는 Solity SN이 있다면 이 단계에서 오류가 발생할 수 있습니다. 
-- 그 경우 중복된 행을 삭제한 후 다시 실행해 주세요.
ALTER TABLE production_records DROP CONSTRAINT IF EXISTS production_records_lumi_sn_key;
ALTER TABLE production_records ADD CONSTRAINT production_records_lumi_sn_key UNIQUE (lumi_sn);

ALTER TABLE production_records DROP CONSTRAINT IF EXISTS production_records_solity_sn_key;
ALTER TABLE production_records ADD CONSTRAINT production_records_solity_sn_key UNIQUE (solity_sn);


-- [테이블 생성]
-- 1. 메인 테이블: 생산 기록 (신규 설치용)
CREATE TABLE IF NOT EXISTS production_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lumi_sn TEXT NOT NULL UNIQUE,
    solity_sn TEXT NOT NULL UNIQUE,
    production_time TEXT NOT NULL,
    operator_name TEXT DEFAULT '',
    note TEXT DEFAULT '',
    deleted_at TEXT DEFAULT NULL,
    CONSTRAINT lumi_sn_not_empty CHECK (length(trim(lumi_sn)) > 0),
    CONSTRAINT solity_sn_not_empty CHECK (length(trim(solity_sn)) > 0),
    CONSTRAINT different_sns CHECK (lumi_sn <> solity_sn)
);

CREATE INDEX IF NOT EXISTS idx_production_records_time
    ON production_records (production_time DESC);

CREATE INDEX IF NOT EXISTS idx_production_records_lumi_sn
    ON production_records (lumi_sn);

CREATE INDEX IF NOT EXISTS idx_production_records_solity_sn
    ON production_records (solity_sn);

-- 2. SN 사용 추적 테이블 (used_sn_codes)
CREATE TABLE IF NOT EXISTS used_sn_codes (
    sn_value TEXT PRIMARY KEY,
    record_id BIGINT NOT NULL REFERENCES production_records(id) ON DELETE CASCADE,
    sn_role TEXT NOT NULL CHECK (sn_role IN ('lumi', 'solity'))
);

-- 3. 앱 설정 테이블 (app_settings)
CREATE TABLE IF NOT EXISTS app_settings (
    settings_key TEXT PRIMARY KEY,
    settings_value TEXT NOT NULL
);

-- 4. Lumi SN 사전 등록 테이블 (lumi_product_sn)
CREATE TABLE IF NOT EXISTS lumi_product_sn (
    lumi_sn TEXT PRIMARY KEY,
    time TEXT DEFAULT ''
);


